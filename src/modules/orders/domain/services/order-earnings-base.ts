import { OrderEntity } from '../entities/order.entity';

/**
 * الأساس الذي تُحتسب عليه أرباح الفنّي — **تعريف واحد لكل مسارات الإتمام**.
 *
 * كان لكل مسار حسابه:
 *
 * | المسار                                | الأساس                    |
 * |---------------------------------------|---------------------------|
 * | `UpdateOrderStatusUseCase` (فنّي/إدارة) | `totalAmount \|\| total`   |
 * | `ConfirmOrderCompletionUseCase` (عميل)  | `total`                   |
 *
 * والفرق ليس شكلياً: `total` في `mapToEntity` يُشتقّ من `payableAmount` حين لا
 * يوجد حقل `total` في القاعدة — ولا يوجد. فبعد استخدام نقاط الولاء يصير
 * `total` هو **الصافي** بينما `totalAmount` يبقى **الإجمالي**.
 *
 * النتيجة: **أجر الفنّي كان يتغيّر بحسب مَن ضغط زرّ الإتمام** — الفنّي نفسه،
 * والعمل نفسه، ومبلغان مختلفان. وهذا لا يُدافَع عنه بأي قراءة.
 *
 * السياسة المعتمدة هنا: **الإجمالي قبل الخصم** (`totalAmount`). الفنّي أدّى
 * الخدمة كاملة، وخصم نقاط الولاء ترويجٌ تتحمّله المنصّة لا الفنّي. وهي أيضاً
 * سياسة المسار الأساسي (تحديث الحالة) الذي يمرّ عبره معظم الإتمامات.
 *
 * ولأنها **قرار عمل لا تفصيل تقني**، فهي معزولة في هذه الدالة: تغييرها إلى
 * الصافي تعديلُ سطر واحد، لا مطاردةُ حسابين في ملفّين.
 */
export function orderEarningsBase(order: OrderEntity): number {
  const anyOrder = order as any;

  // `??` لا `||`: صفرٌ قيمة صحيحة، وتخطّيه يقفز إلى رقم آخر بلا سبب
  const gross = Number(anyOrder.totalAmount ?? order.total ?? 0);
  return Number.isFinite(gross) && gross > 0 ? gross : 0;
}
